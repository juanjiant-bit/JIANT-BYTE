"""(funcbank, flash) the main loop's help texts kept packed: each NAME's text written in its source file as
'#define NAME_TEXT "..."' (not compiled) becomes one LZ4 block (tools/lz4blk.py compress_small, checked by unpacking
it), gz.h gz_get unpacking it when it is read (the main loop's alone; one buffer: a reader takes what it needs before
it asks for another). DRONE CLAY's gestures' lines (clay.c CLAY_HOW), (v1.1b1, VIS's room) the knobs' meanings
(ui_input.c KNOB_HINT), the matrix's names in full (MSRC_FULL, MDST_FULL), FUNC's knobs' tips (eng_lofi.c
FUNC_TIPS_S), HELP's lines (ui_draw.c HELP_S).

  tools/gen_help_z.py SRC/clay.c OUT.h                    (CLAY_HOW)
  tools/gen_help_z.py OUT.h SRC NAME [SRC NAME ...]"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lz4blk


def block(src, name):
    s = Path(src).read_text()
    m = re.search(r"#define " + name + r"_TEXT((?:(?:\s|\\\n)*\"(?:[^\"\\]|\\.)*\")+)", s)
    if not m:
        raise SystemExit(f"{src}: no #define {name}_TEXT")
    raw = "".join(re.findall(r"\"((?:[^\"\\]|\\.)*)\"", m.group(1))).encode().decode("unicode_escape").encode("latin-1") + b"\0"
    z = lz4blk.compress_small(raw)
    assert lz4blk.boot_unpack(z, 0, len(raw))[0] == raw
    L = [f"#define {name}_N {len(raw)}u", f"static const uint8_t {name}_Z[{len(z)}] = {{   /* {len(raw)} B */"]
    for i in range(0, len(z), 24):
        L.append("    " + ", ".join(f"0x{v:02X}" for v in z[i:i + 24]) + ",")
    L += ["};", f"_Static_assert({name}_N <= GZ_MAX, \"gz.h: {name} fits the buffer\");",
          f"#define {name} ((const char *)gz_get({name}_Z, {name}_N))"]
    return L, Path(src).name


def main(argv):
    if not argv[0].endswith(".h"):                 # the old form: clay.c's CLAY_HOW
        argv = [argv[1], argv[0], "CLAY_HOW"]
    out, pairs = argv[0], list(zip(argv[1::2], argv[2::2]))
    L = [f"/* generated by tools/gen_help_z.py from {', '.join(f'{Path(s).name} ({n}_TEXT)' for s, n in pairs)}: "
         "do not edit */", "#pragma once", "#include <stdint.h>", '#include "gz.h"']
    for src, name in pairs:
        L += block(src, name)[0]
    Path(out).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
