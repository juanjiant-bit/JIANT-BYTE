"""(funcbank, flash) the main loop's help texts kept packed: DRONE CLAY's gestures' lines (clay.c CLAY_HOW_TEXT, the
text written there, not compiled) as one LZ4 block (tools/lz4blk.py compress_small, checked by unpacking it), gz.h
gz_get unpacking it when a card shows one (clay.c clay_card_text, ui_lzedit.c: the main loop's alone).

  tools/gen_help_z.py SRC/clay.c OUT.h"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lz4blk


def main(src, out):
    s = Path(src).read_text()
    m = re.search(r"#define CLAY_HOW_TEXT((?:\s*\"(?:[^\"\\]|\\.)*\")+)", s)
    raw = "".join(re.findall(r"\"((?:[^\"\\]|\\.)*)\"", m.group(1))).encode().decode("unicode_escape").encode("latin-1") + b"\0"
    z = lz4blk.compress_small(raw)
    assert lz4blk.boot_unpack(z, 0, len(raw))[0] == raw
    L = ["/* generated by tools/gen_help_z.py from firmware/src/clay.c (CLAY_HOW_TEXT): do not edit */", "#pragma once",
         "#include <stdint.h>", '#include "gz.h"', f"#define CLAY_HOW_N {len(raw)}u",
         f"static const uint8_t CLAY_HOW_Z[{len(z)}] = {{   /* {len(raw)} B */"]
    for i in range(0, len(z), 24):
        L.append("    " + ", ".join(f"0x{v:02X}" for v in z[i:i + 24]) + ",")
    L += ["};", "_Static_assert(CLAY_HOW_N <= GZ_MAX, \"gz.h: CLAY_HOW fits the buffer\");",
          "#define CLAY_HOW ((const char *)gz_get(CLAY_HOW_Z, CLAY_HOW_N))"]
    Path(out).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
