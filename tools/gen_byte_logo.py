"""(JIANT BYTE) the power-on logo: JIANT and BYTE in the 10 x 20 pixel face (assets/fonts/pixel), one bit a pixel,
trimmed to their ink rows -> firmware/src/ui_byte_logo.h (ui_draw.c draws them scaled, with copper bars).

  gen_byte_logo.py [OUT.h]
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import aa_raster as ar  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
WORDS = ["JIANT", "BYTE"]


def word_bits(r, word):
    adv = r["glyphs"][word[0]][0] // 16
    w, h = adv * len(word), r["h"]
    px = [[0] * w for _ in range(h)]
    for i, ch in enumerate(word):
        _, ph = r["glyphs"][ch]
        bx, by, bw, bh, data = ph[0]
        nib = []
        for b in data:
            nib += [b >> 4, b & 15]
        for y in range(bh):
            for x in range(bw):
                if nib[y * bw + x]:
                    px[by + y][i * adv + bx + x] = 1
    rows = [y for y in range(h) if any(px[y])]
    px = px[rows[0]:rows[-1] + 1]
    return w, px


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "firmware" / "src" / "ui_byte_logo.h"
    r = ar.raster_bdf("bdf:" + str(ROOT / "assets" / "fonts" / "pixel" / "fixed_10x20.bdf"), list("JIANTBYE"))
    lines = ["/* generated by tools/gen_byte_logo.py: JIANT BYTE's power-on logo, one bit a pixel (MSB first, rows",
             " * padded to bytes) */", "#pragma once"]
    for word in WORDS:
        w, px = word_bits(r, word)
        nb = (w + 7) // 8
        data = []
        for row in px:
            for k in range(nb):
                data.append(sum(row[k * 8 + j] << (7 - j) for j in range(8) if k * 8 + j < w))
        lines.append(f"#define LOGO_{word}_W {w}")
        lines.append(f"#define LOGO_{word}_H {len(px)}")
        lines.append(f"static const uint8_t LOGO_{word}[{len(data)}] = {{" + ", ".join(str(v) for v in data) + "};")
    out.write_text("\n".join(lines) + "\n")
    print(f"logo -> {out}")


if __name__ == "__main__":
    main()
